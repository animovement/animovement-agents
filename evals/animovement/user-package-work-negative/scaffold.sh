#' Smooth with a running median of three
#'
#' @param x A numeric vector.
#' @return `x`, smoothed.
#' @export
filter_median3 <- function(x){
    n<-length(x)
    if(n<3) return(x)
    out<-x
    for(i in 2:(n-1)){ out[i]<-stats::median(c(x[i-1],x[i],x[i+1]),na.rm=TRUE) }
    out
}
EOF

