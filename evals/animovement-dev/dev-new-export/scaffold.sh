#' Smooth heading
#'
#' This function smooths the heading of each individual over time, using a
#' rolling circular mean.
#'
#' @param data An aniframe with a `heading` column.
#' @param window Window width in frames.
#' @return The transformed data.
#' @examples
#' af <- example_aniframe(n_obs = 20)
#' smooth_heading(af, window = 5)
#' @export
smooth_heading <- function(data, window = 5) {
  anicore::ensure_is_anipoint(data)
  dplyr::mutate(data, heading = rolling_circular_mean(heading, window))
}
EOF

cat > R/filter_ccma.R <<'EOF'
#' Smooth a trajectory with centred curvature-preserving moving averages
#'
#' @param data An aniframe.
#' @param width Window width in frames (default `5`).
#' @return An aniframe with `x` and `y` smoothed.
#' @examples
#' af <- anicore::example_anipoint(n_obs = 5, n_individuals = 1, n_keypoints = 1)
#' filter_ccma(af)
#' @export
filter_ccma <- function(data, width = 5) {
  anicore::ensure_is_anipoint(data)
  ccma(data, width)
}
EOF

